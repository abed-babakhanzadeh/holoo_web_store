"""
نرمال‌سازی متن فارسی برای تطبیق نام استان/شهر.

منابع مختلف (داده‌ی اولیه، ورودی کاربر، دیتابیس قدیمی) گاهی «ي/ك» عربی به‌جای «ی/ک» فارسی و
فاصله‌ی اضافه یا نیم‌فاصله دارند؛ برای مقایسه‌ی نام‌ها همه را به یک شکل واحد می‌بریم.
"""

import re

_TRANSLATION = str.maketrans({
    'ي': 'ی', 'ى': 'ی', 'ك': 'ک', 'ة': 'ه', 'ۀ': 'ه',
    '\u200c': ' ',   # نیم‌فاصله را فاصله‌ی معمولی حساب می‌کنیم
    '\u200f': '', '\u200e': '', '\u00a0': ' ',
})
_SPACES = re.compile(r'\s+')


def normalize_fa(value):
    """ نام را برای مقایسه یکسان می‌کند (فقط برای تطبیق؛ نام ذخیره‌شده تغییر نمی‌کند) """
    if not value:
        return ''
    return _SPACES.sub(' ', str(value).translate(_TRANSLATION)).strip()
