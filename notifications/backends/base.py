"""
قرارداد موتور ارسال.

تنها چیزی که یک موتور می‌بیند: یک مقصد (to) و یک متن (text).
هیچ موتوری نباید بداند پیام مربوط به سفارش است یا کد تایید یا هشدار مدیر — همان‌طور که هیچ
جای دیگر پروژه نباید بداند پیام با پیامک می‌رود یا ایمیل یا هر چیز دیگر.

برای افزودن سرویس جدید: یک فایل کنار همین فایل بساز، از NotificationBackend ارث ببر،
send را پیاده کن و مسیر کلاس را در NOTIFICATION_BACKEND تنظیمات بگذار. هیچ فایل دیگری
از پروژه تغییر نمی‌کند.
"""


class NotificationBackendError(Exception):
    """ خطای قابل‌تلاش‌مجدد موتور ارسال (مشکل شبکه، ۵xx سرویس، محدودیت نرخ و ...) """


class NotificationBackend:
    """ کلاس پایه‌ی همه‌ی موتورهای ارسال """

    def send(self, to: str, text: str) -> str:
        """
        پیام را می‌فرستد.

        بازگشت: شناسه‌ی پیام نزد سرویس (هر رشته‌ای؛ برای پیگیری در لاگ ذخیره می‌شود).
        در صورت شکستِ قابل‌تلاش‌مجدد باید NotificationBackendError بیندازد — نه اینکه
        False برگرداند و نه اینکه سکوت کند. (باگ نسخه‌ی قبلی services/sms.py دقیقاً همین
        بود: شاخه‌ی production همیشه True برمی‌گرداند بدون اینکه چیزی فرستاده باشد.)
        """
        raise NotImplementedError

    def send_template(self, to: str, template_key: str, context: dict, text: str) -> str:
        """
        نسخه‌ی «آگاه از قالب» ارسال. پیش‌فرض همان send() معمولی است (متن آماده‌شده توسط
        templates_registry) — یعنی هیچ بک‌اند فعلی (کنسول، ایمیل، کاوه‌نگار) مجبور به
        پیاده‌سازی این متد نیست.

        فقط بک‌اندهایی که خط‌شان «الگوی تاییدشده‌ی سمت سرویس‌دهنده» است (مثل خط خدماتی
        اشتراکی ملی‌پیامک با bodyId) این متد را بازنویسی می‌کنند، چون آن‌ها به متغیرهای
        خام context نیاز دارند نه به متن نهایی رندرشده (سرویس‌دهنده خودش قالب را با
        متغیرها پر می‌کند و اگر به‌جایش کل متن آماده را به‌عنوان یک متغیر بفرستیم، با خطای
        «عدم تطابق متغیرها» رد می‌شود).
        """
        return self.send(to, text)
